export function normalizeUsStateCode(state: string): string | null {
  const raw = state.trim().toUpperCase();
  if (raw in US_STATE_TAX_RATE_BPS) return raw;
  const byName = US_STATES.find((s) => s.name.toUpperCase() === raw);
  return byName?.code ?? null;
}

