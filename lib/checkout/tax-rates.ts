/** Default estimate when a country has no explicit rate. */
export const DEFAULT_INTL_TAX_RATE_BPS = 1500;

export function resolveCountryTaxRateBps(country: string): number {
  const code = country.trim().toUpperCase();
  if (code === "US") return 0;
  return COUNTRY_TAX_RATE_BPS[code] ?? DEFAULT_INTL_TAX_RATE_BPS;
}

export function resolveTaxRateBps(state: string, country = "US"): number {
  const code = country.toUpperCase();
  if (code !== "US") return resolveCountryTaxRateBps(code);
  const stateCode = normalizeUsStateCode(state);
  if (!stateCode) return 0;
  return US_STATE_TAX_RATE_BPS[stateCode] ?? 0;
}
